class Command(BaseCommand):
    help = 'Populate database with 100 real travel destinations (clears existing data)'

    def handle(self, *args, **options):
        self.stdout.write('Clearing existing destinations...')
        count_before = Destination.objects.count()
        Destination.objects.all().delete()
        self.stdout.write(f'  Removed {count_before} existing destinations.')

        self.stdout.write('Creating 100 destinations...')
        created = 0
        used_slugs = set()
        for dest_data in DESTINATIONS:
            name = dest_data.get('name', '')
            if name in DESTINATION_REGIONS:
                dest_data['region'] = DESTINATION_REGIONS[name]
            if name in PRICE_DATA:
                dest_data.update(PRICE_DATA[name])
            if name in DESCRIPTIONS_MK:
                dest_data['description_mk'] = DESCRIPTIONS_MK[name]
            base_slug = make_slug(name)
            slug = base_slug
            counter = 2
            while slug in used_slugs:
                slug = f'{base_slug}-{counter}'
                counter += 1
            used_slugs.add(slug)
            dest_data['slug'] = slug
            Destination.objects.create(**dest_data)
            created += 1

        self.stdout.write(
            self.style.SUCCESS(f'Successfully created {created} destinations.')
        )
        if created != 100:
            self.stdout.write(
                self.style.WARNING(f'Expected 100, got {created}. Check DESTINATIONS list for duplicates.')
            )
